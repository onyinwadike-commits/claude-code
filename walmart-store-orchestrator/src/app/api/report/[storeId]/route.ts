function getSectionName(key: string): string {
  const names: Record<string, string> = {
    A: 'Fresh',
    B: 'Consumables',
    C: 'Health & Wellness',
    D: 'General Merchandise',
    E: 'Entertainment',
    F: 'Financial Services',
    G: 'Front End',
    H: 'OGP/Digital',
    I: 'Inventory',
    J: 'Asset Protection',
    K: 'People',
  };
  return names[key] || key;
}
