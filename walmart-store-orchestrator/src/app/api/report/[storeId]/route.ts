import { NextRequest, NextResponse } from 'next/server';
import { getStoreById } from '@/data/stores';
import { generateStoreReport } from '@/lib/llm/report-generator';
import { StoreReport, AgentName } from '@/lib/llm/types';

// In-memory cache for demo (use Redis in production)
const reportCache = new Map<string, { report: StoreReport; timestamp: number }>();
const CACHE_TTL_MS = 5 * 60 * 1000; // 5 minutes

export async function GET(
  request: NextRequest,
  { params }: { params: Promise<{ storeId: string }> }
) {
  try {
    const { storeId } = await params;

    // Validate store exists
    const store = getStoreById(storeId);
    if (!store) {
      return NextResponse.json(
        { error: 'Store not found', storeId },
        { status: 404 }
      );
    }

    // Check cache
    const cached = reportCache.get(storeId);
    if (cached && Date.now() - cached.timestamp < CACHE_TTL_MS) {
      return NextResponse.json({
        report: cached.report,
        cached: true,
        cacheAge: Math.round((Date.now() - cached.timestamp) / 1000),
      });
    }

    // Check for required API keys
    const requiredKeys = [
      'PERPLEXITY_API_KEY',
      'XAI_API_KEY',
      'GOOGLE_AI_API_KEY',
      'ANTHROPIC_API_KEY',
      'OPENAI_API_KEY',
      'DEEPSEEK_API_KEY',
    ];

    const missingKeys = requiredKeys.filter((key) => !process.env[key]);
    if (missingKeys.length > 0) {
      // Return mock report for demo when API keys are missing
      return NextResponse.json({
        report: generateMockReport(store),
        cached: false,
        demo: true,
        message: 'Demo mode: API keys not configured',
      });
    }

    // Generate report
    const report = await generateStoreReport(store);

    // Cache the report
    reportCache.set(storeId, { report, timestamp: Date.now() });

    return NextResponse.json({
      report,
      cached: false,
    });
  } catch (error) {
    console.error('Report generation error:', error);
    return NextResponse.json(
      {
        error: 'Failed to generate report',
        message: error instanceof Error ? error.message : 'Unknown error',
      },
      { status: 500 }
    );
  }
}

// POST to force regeneration
export async function POST(
  request: NextRequest,
  { params }: { params: Promise<{ storeId: string }> }
) {
  try {
    const { storeId } = await params;

    const store = getStoreById(storeId);
    if (!store) {
      return NextResponse.json(
        { error: 'Store not found', storeId },
        { status: 404 }
      );
    }

    // Clear cache for this store
    reportCache.delete(storeId);

    // Check for required API keys
    const requiredKeys = [
      'OPENAI_API_KEY', // At minimum need one key
    ];

    const hasAnyKey = requiredKeys.some((key) => process.env[key]);
    if (!hasAnyKey) {
      return NextResponse.json({
        report: generateMockReport(store),
        cached: false,
        demo: true,
        message: 'Demo mode: API keys not configured',
      });
    }

    // Generate fresh report
    const report = await generateStoreReport(store);

    // Cache the new report
    reportCache.set(storeId, { report, timestamp: Date.now() });

    return NextResponse.json({
      report,
      cached: false,
      regenerated: true,
    });
  } catch (error) {
    console.error('Report regeneration error:', error);
    return NextResponse.json(
      {
        error: 'Failed to regenerate report',
        message: error instanceof Error ? error.message : 'Unknown error',
      },
      { status: 500 }
    );
  }
}

